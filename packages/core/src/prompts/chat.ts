/**
 * 聊天回复的**长度约束**（★ 2026-10-20，change: `make-her-brief`）。
 *
 * ## 为什么放代码里，不放 `persona/talk_system.md`
 *
 * `talk_system.md` 里本来就有长度规则（问候 1-3 句 / 日常 3-6 句），但它
 * **只在 seed 角色包时**被拼进 `persona.system_prompt`：
 * 改了 md 不重导就**不生效**（库里还是旧文本），而且重导有覆盖用户自定义人设的风险。
 *
 * 长度是**产品级约束**（我们决定她别啰嗦），不是角色设定（那是用户的东西）——
 * 所以它必须**改动即生效、且不受 DB 里的旧人设影响**。
 *
 * ## 为什么能硬起来
 *
 * 原来的规则是"参考"（"回复长度与用户输入成正比"），模型对"参考"基本无视。
 * 这里改成**默认值 + 例外条件**：默认 ≤3 句，只有"用户在问步骤/要说明"才可以长。
 * 并且明确 **不因"想把话说完整"而加长** —— 那是最常见的变长借口。
 */
