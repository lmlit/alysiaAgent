/**
 * 上下文压缩的提示词资产（★ 2026-10-20，change: `put-dropped-turns-back`）。
 *
 * 与 `prompts/memory.ts` 的区别：
 *   - `memory.ts` 那些是**长期记忆**的提取/摘要（会话结束、画像、深度重写）
 *   - 本文件是**当前会话**的上下文压缩（被截断丢弃的轮次 → 一段"更早的对话"）
 *
 * ⚠️ 两者最容易搞混，后果是"用长期摘要的口径压上下文"：那会把她当下的语气、
 * 承诺、正在做的事一起抹平。上下文压缩只保**事实**，不保文风。
 */

/**
 * 系统提示：把一段对话压成"可继续对话用的回忆"。
 *
 * 三条硬约束（对应 spec §6.5 契约）：
 * ① **只留事实**：说了什么、决定了什么、答应了什么、还在等什么 —— 不保留语气与措辞
 * ② **不编造**：原文没说的不补（压缩最容易"合理想象"，那是记忆污染）
 * ③ **可续接**：写成第三人称要点，让她读完知道"刚才聊到哪、还有什么没做"
 */
export const CONTEXT_COMPACT_SYSTEM_PROMPT =
  '你是一个对话压缩器。把下面这段**较早的对话**压成一份可续接的回忆。'
  + '要求：① 只保留**事实**——聊了什么、决定了什么、答应了什么、还有什么没做；'
  + '不保留语气、不模仿口吻、不抄原句；'
  + '② **不许编造**：原文里没有的信息一律不补，宁可漏也不要猜；'
  + '③ 写成**第三人称要点**（3-6 行，每行一句），不要问候、不要注释、不要 JSON；'
  + '④ 总长不超过 400 字。直接输出要点本身。';

/**
 * 已有压缩摘要时的**增量合并**提示。
 *
 * 为什么需要：长会话会压缩很多次。若每次都只压新丢的那批，摘要会无限累加；
 * 若直接覆盖，早先的回忆就丢了。所以是「旧摘要 + 新丢弃」→ 一份新摘要。
 */
export const CONTEXT_COMPACT_MERGE_SYSTEM_PROMPT =
  '你是一个对话压缩器。你手上有一份**已有的回忆摘要**，又来了**更晚一些**的对话片段。'
  + '请把它们合并成一份新的回忆摘要。'
  + '要求：① 只保留**事实**（聊了什么、决定了什么、答应了什么、还有什么没做）；'
  + '② **不许编造**，原文没有的不补；'
  + '③ 越早、越不重要的细节可以淡出——但**未完成的承诺/待办不许丢**；'
  + '④ 写成第三人称要点（3-6 行），总长不超过 400 字。直接输出要点本身。';
