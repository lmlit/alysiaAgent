/**
 * 自省事实的**人称归一**（★ 2026-10-25，change: `first-person-self-facts`）
 *
 * ## 为什么需要它
 *
 * `character_facts` 里存的是"她对自己的认识"，会被**原样注入【关于我】块**。
 * 所以它必须是**第一人称**（"我其实很享受被需要的时刻"）——
 * 否则她读到的是"昔涟怎样怎样"，等于**用别人的名字说自己**。
 *
 * 生产实测（2026-10-25）：48 条里有 **5 条是第三人称**：
 *
 * ```
 * 昔涟昨天给用户发了很多消息。
 * 昔涟会对用户表达亲昵/肉麻的话
 * 昔涟可能处于容易劳累或忙碌的状态
 * ```
 *
 * prompt 里本来就写了「第一人称」，但模型仍会漂移。
 * **在写入端做确定性归一**，比指望 prompt 自觉可靠 —— 这是本仓反复验证过的一条。
 *
 * ## 边界（有意保守）
 *
 * 只处理「**开头**是第三人称自称」的情形：
 * - `昔涟/小昔涟…` → `我…`
 * - `她…`（作为主语开头）→ `我…`
 *
 * **不动**中间出现的第三人称（"我告诉她"是正常的），也**不动**以「用户/轻月」开头的事实
 * （那是被错放进来的"关于他"，属另一类问题，不该用替换伪装成自省）。
 */
export function normalizeSelfFact(raw: string): string {
  let s = String(raw ?? '').trim();
  if (!s) return s;

  // 1) 「昔涟…」开头 → 「我…」（最常见）
  s = s.replace(/^(小)?昔涟/u, '我');

  // 2) 「她…」开头（`她` 作主语）→ 「我…」
  //    限定后接谓词/助词，避免把「她」当宾语误伤（如「我…」不受影响；「她们」不动）
  s = s.replace(/^她(?=[的会把在是对有也想不很常总可正又])/u, '我');

  return s.trim();
}

/** 是否需要归一（给存量清洗用；`false` = 已是第一人称/无需动） */
export function needsSelfFactNormalize(raw: string): boolean {
  return normalizeSelfFact(raw) !== String(raw ?? '').trim();
}
